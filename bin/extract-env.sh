#!/usr/bin/env bash
#
# 从各镜像 Dockerfile 的 ARG 行抽取默认值，生成根目录 .env.laradock。
# 每行 NAME=default，按镜像分组（# ===== <image> =====）。
# 跨 Dockerfile 重名的 ARG 只保留首次出现（SYNC_DIRS 顺序）。
# 无默认值的 ARG 会加注释标记，构建时需显式传入。
# 默认值若是纯变量引用（如 ${LARADOCK_PHP_VERSION}），归到被
# 引用的变量名下，以便与其自身的 ARG 声明去重。
#
# 用法: bin/extract-env.sh

set -euo pipefail

ROOT_DIR="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)"
# shellcheck source=bin/.sync-config.sh
source "$(dirname "${BASH_SOURCE[0]}")/.sync-config.sh"
out_env="${ROOT_DIR}/.env.laradock"

shopt -s extglob   # 下面用 +([[:space:]]) 剥 ARG 后的空白

# 全部内容先攒在数组里，最后一次写盘；出错时旧文件原样保留
out_lines=()

# 源文件列表右侧注释的对齐列宽
src_width=0
for image in "${SYNC_DIRS[@]}"; do
  path="${image}/Dockerfile"
  (( ${#path} > src_width )) && src_width=${#path}
done

# 文件头横幅：声明这是生成文件，并指向该手改的 preference 文件
out_lines+=(
  "###########################################################"
  "##  AUTO-GENERATED FILE - DO NOT EDIT BY HAND"
  "##"
  "##  Generated by : bin/extract-env.sh"
)
label="Sources      :"
for image in "${SYNC_DIRS[@]}"; do
  out_lines+=( "$(printf '##  %s %-*s  (ARG defaults)' "${label}" "${src_width}" "${image}/Dockerfile")" )
  label="              "   # 后续行只保留缩进，标签不重复
done
out_lines+=(
  "##"
  "##  Duplicate ARG names keep the first hit in SYNC_DIRS order."
  "##  To change a value, put it in .env.laradock.preference"
  "##  (it wins on conflict) - bin/build-args.sh merges both."
  "###########################################################"
)

declare -A seen=()   # 已出现的变量名，用于跨镜像去重
for image in "${SYNC_DIRS[@]}"; do
  dockerfile="${ROOT_DIR}/${image}/Dockerfile"
  if [[ ! -f "${dockerfile}" ]]; then
    echo "!! ${image}/Dockerfile not found - run bin/sync-upstream.sh first" >&2
    exit 1
  fi
  # 用命令替换而不是 < <(grep ...)：进程替换的退出码 set -e 看不见，
  # grep 一个 ARG 都没抓到时会静默产出空分组。
  if ! arg_text="$(grep '^ARG ' "${dockerfile}")"; then
    echo "!! no ARG lines in ${image}/Dockerfile" >&2
    exit 1
  fi
  mapfile -t arglines <<< "${arg_text}"

  section=()
  for argline in "${arglines[@]}"; do
    argline="${argline#ARG}"
    argline="${argline##+([[:space:]])}"
    name="${argline%%=*}"
    default=""
    [[ "${argline}" == *=* ]] && default="${argline#*=}"
    # 默认值是纯变量引用时，归到被引用的变量名下
    if [[ "${default}" =~ ^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$ ]]; then
      name="${BASH_REMATCH[1]}"
      default=""
    fi

    [[ -v seen["${name}"] ]] && continue
    seen["${name}"]=1

    if [[ -z "${default}" ]]; then
      section+=( "${name}=    # no default in Dockerfile" )
    else
      section+=( "${name}=${default}" )
    fi
  done

  # 该镜像的 ARG 全被前面的镜像去重掉时分组为空，不输出标题
  if (( ${#section[@]} )); then
    out_lines+=( "" "# ===== ${image} =====" "${section[@]}" )
  fi
done

printf '%s\n' "${out_lines[@]}" > "${out_env}"
# 先赋值再 echo：写成 echo "$(grep -c ...)" 时 grep 失败会被 echo 的 0 吞掉
count="$(grep -cE '^[A-Za-z_][A-Za-z0-9_]*=' "${out_env}")"
echo "==> Wrote ${count} vars to .env.laradock"
